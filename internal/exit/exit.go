// Package exit — коды выхода yk-kai.
//
// Это контракт с вызывающим, а не вежливость: команду зовёт агент, и по коду
// он решает, что делать дальше, не разбирая текст. Точная причина всегда
// лежит в JSON-конверте.
//
// Коды 2 и 3 совпадают по смыслу с sec и ci-kai (die → 2, dieNotFound → 3) —
// во всей семье CLI они значат одно и то же.
package exit

const (
	// OK — операция выполнена и проверена.
	OK = 0

	// NotApplied — YouTrack принял запрос, но результат не тот, которого
	// просили: поле не проставилось после дожима, задача не прицепилась к
	// доске. Отличается от Tool тем, что инструмент исправен, а состояние в
	// трекере — нет.
	NotApplied = 1

	// Tool — ошибка инструмента или аргументов: нет токена, YouTrack отверг
	// авторизацию, неизвестная команда, недопустимое значение поля.
	Tool = 2

	// NotFound — задачи, статьи или пользователя с таким id нет.
	NotFound = 3

	// Timeout — YouTrack не ответил за отведённое время. Ничего не решено,
	// операции идемпотентны, звать ещё раз.
	Timeout = 4
)
